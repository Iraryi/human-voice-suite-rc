#!/usr/bin/env node
/**
 * `npm run bench:report`
 *
 * Renders `BENCHMARK_RESULTS.md` from a stored run.
 *
 * The report leads with what was *not* measured, because a benchmark's
 * limitations are the part a reader cannot reconstruct from the numbers. It
 * quotes the corpus hash and the run file so every figure can be traced back, and
 * it never presents an aggregate across the four scores.
 */

