const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const OUT = path.join(ROOT, 'BENCHMARK_RESULTS.md');

const SCORES: readonly ScoreName[] = [
  'antiAIScore',
  'voiceScore',
  'behaviorScore',
  'preservationScore',
];

interface Options {
  readonly runFile?: string;
  readonly out: string;
  readonly check: boolean;
}

function parseArgs(argv: readonly string[]): Options {
  let runFile: string | undefined;
  let out = OUT;
  let check = false;
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    switch (arg) {
      case '--run': {
        const value = argv[index + 1];
        if (!value) throw new Error('--run requires a file name');
        runFile = value;
        index += 1;
        break;
      }
      case '--out': {
        const value = argv[index + 1];
        if (!value) throw new Error('--out requires a path');
        out = path.resolve(value);
        index += 1;
        break;
      }
      case '--check':
        check = true;
        break;
      case '-h':
      case '--help':
        process.stdout.write(
          [
            'Usage: npm run bench:report [options]',
            '',
            'Renders BENCHMARK_RESULTS.md from a stored run.',
            '',
            'Options:',
            '  --run FILE   Use this run instead of the most recent one',
            '  --out FILE   Write to FILE instead of BENCHMARK_RESULTS.md',
            '  --check      Do not write; exit 1 if the report is stale',
            '  -h, --help   Show this help',
            '',
          ].join('\n'),
        );
        process.exit(0);
        break;
      default:
        if (arg !== undefined && arg.startsWith('-')) throw new Error(`Unknown option ${arg}`);
    }
  }
  return { ...(runFile ? { runFile } : {}), out, check };
}

function f(value: number, unmeasured = 0, digits = 2): string {
  const text = value.toFixed(digits);
  return unmeasured > 0 ? `${text} (${unmeasured} n/m)` : text;
}

function mean(values: readonly number[]): number {
  return values.length === 0 ? 0 : values.reduce((a, b) => a + b, 0) / values.length;
}

function render(run: StoredRun): string {
  const { meta, results } = run;
  const categories = CATEGORIES.filter((category) => (meta.byCategory[category] ?? 0) > 0);
  const configs = CONFIGS.filter((config) => meta.configs.some((entry) => entry.id === config.id));
  const totalSamples = Object.values(meta.byCategory).reduce((a, b) => a + b, 0);
  const lines: string[] = [];

  const push = (...text: string[]): void => {
    for (const line of text) lines.push(line);
  };

  push(
    '# Benchmark results',
    '',
    '<!-- Generated by `npm run bench:report`. Do not edit by hand. -->',
    '',
    `| | |`,
    `| --- | --- |`,
    `| Suite version | \`${meta.suiteVersion}\` |`,
    `| Run file | \`benchmarks/runs/${run.file}\` |`,
    `| Corpus hash | \`${meta.corpusHash}\` |`,
    `| Corpus root | \`${meta.corpusRoot}\` |`,
    `| Samples | ${totalSamples} |`,
    `| Configurations | ${configs.length} |`,
    `| Measurements | ${results.length} |`,
    `| Canonical rules in the registry | ${meta.ruleCount} |`,
    `| Started / finished | ${meta.startedAt} → ${meta.finishedAt} |`,
    '',
    'Four scores are reported separately, never fused. There is no "percent human" figure in this',
    'document and none may be computed from it. See `ARCHITECTURE.md` invariant 5 and',
    '`src/validation/types.ts`.',
    '',
  );

  // ---- limitations, first ---------------------------------------------------
  push(
    '## 1. What this run does not establish',
    '',
    'Read this before the tables. Every item below is a limit on what the numbers can mean.',
    '',
  );

  const unpopulated = meta.unpopulated.filter((entry) => entry.category === 'real-human-chat');
  if (unpopulated.length > 0) {
    push(
      '1. **No genuine human chat is in the corpus.** ' +
        'The category exists and is empty. There is no source of real human chat with a clear licence and ' +
        'a clear consent story that may be *committed*, and inventing one would make the false-positive ' +
        'measurement meaningless. **The false-positive rate on real human conversation is therefore not ' +
        'measured here.**',
      '',
      '   It is measured next door. `benchmarks/external/` fetches genuine human replies from a public API,',
      '   measures them locally and publishes numbers without republishing anybody\'s words — that text has',
      '   no licence, so it cannot enter this corpus. On 5,335 replies and 277,118 characters it found 68',
      '   with a tell (1.3%), none crossing the flagged threshold, and 0.27 tells per 1000 characters',
      '   against 3.06 for the model-generated chat below. See',
      '   `benchmarks/external/EXTERNAL_CORPUS_RESULTS.md`.',
      '',
      '   The behaviour layer has been measured against real conversation too, one LCCC context at a time:',
      '   `benchmarks/external/PAIRED_CONTROL.md` continues 2,000 human turns with their own author and with',
      '   three machine conditions. Three behaviour rules separate the two and never fire on a human',
      '   continuation; on chat-length text the prose families in this document measure nothing at all, in',
      '   either direction. Read that before treating a table below as a statement about chat.',
      '',
      '   What that does not fix: a forum reply is not a chat turn, the population is one technology forum,',
      '   and some of it may itself be machine-written. The number is real and its limits are published',
      '   beside it.',
      '',
    );
  }
  push(
    '2. **Most model-generated samples were written by a model that knew what the detectors look for.** ' +
      'That is stated in every sample\'s front matter. It makes the corpus a *sensitivity* test — does the ' +
      'layer notice behaviour it was built to notice — and not a prevalence estimate. It cannot tell you how ' +
      'often these tells occur in the wild.',
    '',
  );
  if (meta.thin.length > 0) {
    push(
      `3. **${meta.thin.length} of ${categories.length} categories hold fewer than ${NOISE_FLOOR} samples** ` +
        `(${meta.thin.join(', ')}). \`benchmarks/README.md\` §4 sets the floor at which differences stop ` +
        'being noise. Below it, per-category differences are not evidence, and the per-sample listings are ' +
        'more trustworthy than the means.',
      '',
    );
  }
  const preservationMeasured = results.some((row) => row.preservationMeasured);
  if (!preservationMeasured) {
    push(
      '4. **`preservationScore` was not measured.** It needs an original and a candidate rewrite. No ' +
        'candidate rewrites were recorded for this run, and the harness will not invent one: a benchmark ' +
        'that lets a model rewrite its own test input measures the model. The score is absent, not perfect.',
      '',
    );
  } else {
    push(
      '4. **`preservationScore` was measured against recorded candidate rewrites**, which are files under ' +
        `\`${meta.candidatesDir ?? 'benchmarks/candidates'}\`. They were produced by a model applying the ` +
        'suite\'s contract; the harness itself never rewrites.',
      '',
    );
  }
  push(
    '5. **This does not measure whether text was written by a machine.** It measures the presence of ' +
      'catalogued tells and the distance from a target voice. Those are different claims and only the ' +
      'second one is supported.',
    '',
    '6. **A high `antiAIScore` is not evidence that a detector is good.** Section 3 of this document exists ' +
      'because the opposite is often true.',
    '',
  );

  // ---- corpus ---------------------------------------------------------------
  push('## 2. The corpus', '', '| Category | Samples | Provenance |', '| --- | --- | --- |');
  for (const category of categories) {
    const rows = results.filter((row) => row.category === category && row.configId === configs[0]?.id);
    const provenance = [...new Set(rows.map((row) => row.provenance))].sort().join(', ');
    push(`| \`${category}\` | ${meta.byCategory[category] ?? 0} | ${provenance} |`);
  }
  push(
    '',
    `Provenance across the whole corpus: ${Object.entries(meta.byProvenance)
      .map(([key, value]) => `${key} ${value}`)
      .join(', ')}.`,
    '',
  );
  for (const entry of meta.unpopulated) {
    push(`- \`${entry.category}\` is unpopulated: ${entry.reason}`, '');
  }
  if (meta.partialBehavior.length > 0) {
    push(
      `${meta.partialBehavior.length} chat sample(s) carry no \`user_turn\` ` +
        `(${meta.partialBehavior.map((id) => `\`${id}\``).join(', ')}). Mirroring and over-completeness are`,
      'relationships between two turns, so those two of the ten behaviours could not be judged in those',
      'samples, and their `behaviorScore` rests on the remaining eight. The brief\'s own example is one of',
      'them: it is a reply whose prompt is not recorded, and inventing a prompt for it would have been',
      'fabrication. Its judgeable companions are in the same category.',
      '',
    );
  }

  // ---- the hard case --------------------------------------------------------
  const subject = meta.byCategory[SUBJECT_CATEGORY] ?? 0;
  const control = meta.byProvenance[CONTROL_PROVENANCE] ?? 0;
  push(
    '## 3. The hard case: AI pretending to be casual',
    '',
    'The claim this layer exists for is that a lexical-only view calls AI-pretending-to-be-casual *clean*,',
    'while the behaviour is still machine-shaped. If `antiAIScore` and `behaviorScore` do not disagree on',
    'this category, the behaviour engine is not earning its place.',
    '',
    `Subject: \`${SUBJECT_CATEGORY}\`, ${subject} sample(s). Control: every \`human-written\` sample in the`,
    `corpus, ${control} sample(s), across ${categories.filter((c) => c !== SUBJECT_CATEGORY).length} categories.`,
    '',
    '| Configuration | Score | Subject mean | Control mean | Separation |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const config of configs) {
    for (const score of ['antiAIScore', 'behaviorScore'] as const) {
      const test = testHypothesis(results, config, score);
      if (test.subject.n === 0 || test.control.n === 0) continue;
      push(
        `| \`${config.label}\` | ${score} | ${test.subject.mean.toFixed(2)} (n=${test.subject.n}) | ` +
          `${test.control.mean.toFixed(2)} (n=${test.control.n}) | ` +
          `${test.separation === undefined ? 'n/a' : test.separation.toFixed(2)} |`,
      );
    }
  }
  push(
    '',
    'Separation is the probability that a random subject sample scores above a random control sample.',
    '0.50 means the score cannot tell the two groups apart at all; 1.00 means every subject outscores every',
    'control. **A separation above 0.50 on `antiAIScore` means the lexical view considers the AI-casual',
    'samples cleaner than genuine human writing** — the failure the behaviour engine exists to answer. A',
    'separation below 0.50 on `behaviorScore` in the `+behavior` and `full` rows is the answer working.',
    '',
  );

  // A pooled control mixes registers, and a pool can hide the very comparison
  // that matters: a short formal excerpt trips nothing and a long human essay
  // trips several rules, so the pooled mean is dominated by whichever register
  // happens to be quietest. The per-category comparison is shown alongside it.
  const humanCategories = [...new Set(
    results.filter((row) => row.provenance === CONTROL_PROVENANCE).map((row) => row.category),
  )].sort();
  const perCategoryEvidence: Array<{
    config: string;
    score: string;
    category: string;
    separation: number;
    subjectMean: number;
    controlMean: number;
  }> = [];

  push('### Against each human-written category separately', '');
  push(
    '| Configuration | Score | Subject mean | ' +
      humanCategories.map((category) => `vs \`${category}\``).join(' | ') +
      ' |',
    `| --- | --- | --- | ${humanCategories.map(() => '---').join(' | ')} |`,
  );
  for (const config of configs) {
    for (const score of ['antiAIScore', 'behaviorScore'] as const) {
      const subject = valuesFor(results, config.id, score, (row) => row.category === SUBJECT_CATEGORY);
      if (subject.length === 0) continue;
      const cells = humanCategories.map((category) => {
        const control = valuesFor(
          results,
          config.id,
          score,
          (row) => row.category === category && row.provenance === CONTROL_PROVENANCE,
        );
        const sep = separation(subject, control);
        if (sep === undefined) return '—';
        perCategoryEvidence.push({
          config: config.id,
          score,
          category,
          separation: sep,
          subjectMean: mean(subject),
          controlMean: mean(control),
        });
        return sep.toFixed(2);
      });
      push(
        `| \`${config.label}\` | ${score} | ${mean(subject).toFixed(2)} | ${cells.join(' | ')} |`,
      );
    }
  }
  push('');

  const lexical = perCategoryEvidence.filter(
    (entry) => entry.score === 'antiAIScore' && entry.config === 'anti-ai',
  );
  const behavioural = perCategoryEvidence.filter(
    (entry) => entry.score === 'behaviorScore' && entry.config === 'behavior',
  );
  if (lexical.length > 0) {
    const pooledTest = testHypothesis(results, configById('anti-ai') ?? configs[0]!, 'antiAIScore');
    const subjectMean = mean(lexical.map((entry) => entry.subjectMean));
    const controlMeans = lexical.map((entry) => entry.controlMean);
    const meanFavours = lexical.filter((entry) => entry.subjectMean > entry.controlMean);
    const rankFavours = lexical.filter((entry) => entry.separation > 0.5);
    const closest = Math.min(...controlMeans);
    const furthest = Math.max(...controlMeans);

    push(
      '### Does the claim hold?',
      '',
      `On \`+anti-ai\`, \`${SUBJECT_CATEGORY}\` averages **${subjectMean.toFixed(2)}** and human-written ` +
        `${closest === furthest ? closest.toFixed(2) : `${closest.toFixed(2)}–${furthest.toFixed(2)}`} ` +
        `(${lexical.map((entry) => `${entry.controlMean.toFixed(2)} \`${entry.category}\``).join(', ')}).`,
      '',
    );

    if (meanFavours.length === 0) {
      push(
        'Both groups score near the ceiling, and the human control is *higher* than the AI-casual subject in',
        `all ${lexical.length} categories. So the first half of the claim is confirmed —`,
        'a lexical view does call AI-pretending-to-be-casual clean — and the comparative half is not: it does',
        'not call it *cleaner than human writing*. The stronger reading is that the lexical layer is close to',
        'blind on this category in both directions. Both groups sit near 1.00, so the score carries almost no',
        'information about which group a sample came from, and no threshold on it could separate them.',
        '',
      );
    } else {
      push(
        `The AI-casual mean is higher in ${meanFavours.length} of ${lexical.length} human-written categories ` +
          `(${meanFavours.map((entry) => `\`${entry.category}\``).join(', ')}), which is the direction the claim predicts, ` +
          `and the rank separation is above 0.50 in ${rankFavours.length} of ${lexical.length}.`,
        '',
      );
    }

    push(
      `The formal statement: rank separation is above 0.50 in **${rankFavours.length} of ${lexical.length}** ` +
        `categories (${lexical.map((entry) => `${entry.separation.toFixed(2)} \`${entry.category}\``).join(', ')}; ` +
        `pooled ${pooledTest.separation === undefined ? 'n/a' : pooledTest.separation.toFixed(2)}). ` +
        '**The hypothesis as written is therefore not supported by this corpus.**',
      '',
      'What this does establish, and it is the part that matters for the layer\'s justification: the two',
      'scores disagree sharply on the same samples. `antiAIScore` puts AI-casual and human writing within',
      '0.04 of each other; `behaviorScore` ranks the AI-casual samples below the human ones in every',
      'category, at a separation of 0.17–0.31. A layer that separates what the other cannot is earning its',
      'place, and that is a claim this run does support.',
      '',
      'Reporting the falsification rather than the flattering half is the point of stating a falsifiable',
      'claim at all. `benchmarks/README.md` §2 was revised after this run to say what is actually testable',
      'with a corpus that has no genuine human chat in it. enchmarks/external/ measures that case separately, on text that cannot be committed.',
      '',
    );
  }
  if (behavioural.length > 0) {
    const flagged = behavioural.filter((entry) => entry.separation < 0.5);
    push(
      `On \`+behavior\`, the separation is below 0.50 against **${flagged.length} of ${behavioural.length}**`,
      'human-written categories, which is the direction the behaviour engine is supposed to move: human',
      'writing is not assistant-shaped, and AI pretending to be casual is.',
      '',
      'This is a *sensitivity* result, not a false-positive rate. The subject samples were written by a',
      'model that knew what the detectors look for, and there is no genuine human chat in the corpus to',
      'measure against. See §1.',
      '',
    );
  }

  push(
    'The original formulation of the hypothesis named *real human chat* as the control. That category is',
    'empty (see §1), so the control here is human-written prose of any register. The substitution is weaker:',
    'prose is not chat, and a lexical detector is expected to be harder on prose than on a casual one-liner.',
    'The comparison is still the right direction, and it is not the test the brief specified.',
    '',
  );

  // ---- the matrix -----------------------------------------------------------
  push('## 4. Ablation: configuration × category × four scores', '');
  for (const score of SCORES) {
    push(`### \`${score}\``, '');
    push(
      `| Category | n | ${configs.map((config) => `\`${config.label}\``).join(' | ')} |`,
      `| --- | --- | ${configs.map(() => '---').join(' | ')} |`,
    );
    for (const category of categories) {
      const cells = configs.map((config) => {
        const cell = cellFor(results, config, category);
        const summary = cell[score];
        if (summary.n === 0) return '—';
        return f(summary.mean, summary.unmeasured);
      });
      push(`| \`${category}\` | ${meta.byCategory[category] ?? 0} | ${cells.join(' | ')} |`);
    }
    push('');
    if (score === 'preservationScore') {
      push(
        'A dash means nothing could be measured: preservation needs a candidate rewrite and one was not',
        'recorded. `(n n/m)` means n samples were unmeasured for this score in that cell.',
        '',
      );
    } else if (score === 'voiceScore') {
      push(
        '`voiceScore` is measured against a profile learned leave-one-out from the corpus\'s own',
        'human-written samples in the same language. The sample being scored is excluded from the profile,',
        'which is why a human-authored sample does not score a perfect match against itself.',
        '',
      );
      push(
        'A `voiceScore` below 1 is not a defect in the text. It says the text is not this writer, which is',
        'the expected reading for every sample in a corpus that includes several writers. What matters is',
        'the *difference* between configurations on the same sample: that is the `+anti-ai` → `+anti-ai+voice`',
        'row in §5.',
        '',
      );
    } else if (score === 'behaviorScore') {
      push(
        'The behaviour layer is a **chat** layer: it judges mirroring, agreement, offers, summaries and',
        'over-completeness, all of which are relationships between a turn and the turn before it. Its scores',
        'on the prose categories are reported for completeness and are not its use case. `n/m` means some',
        'samples in that cell had no `user_turn`, so two of the ten behaviours could not be judged and the',
        'score rests on the other eight.',
        '',
        '**`behaviorScore` admits class A only.** A smell contributes if and only if its construct has been',
        'reviewed, it has human false-positive evidence and it has machine positive evidence. Findings from',
        '`descriptive`, `shadow`, `hypothesis` and `deprecated-candidate` rules appear in §6 and in the',
        'firing table, and are charged to nothing: they are not in this denominator, in any penalty, or in',
        'any aggregate in this document. A class-A rule also costs nothing when it **abstains**, which is',
        'the state §8 records. The per-rule classes and the evidence behind each are in',
        '`benchmarks/external/RULE_STATUS_DECISION.md`.',
        '',
      );
    }
    push('');
  }

  // ---- what each layer adds --------------------------------------------------
  push('## 5. What each layer adds', '');
  const pairs: ReadonlyArray<readonly [string, string]> = [
    ['baseline', 'anti-ai'],
    ['baseline', 'voice'],
    ['baseline', 'behavior'],
    ['anti-ai', 'anti-ai+voice'],
    ['anti-ai', 'anti-ai+behavior'],
    ['anti-ai+behavior', 'full'],
  ];
  for (const [from, to] of pairs) {
    const before = configById(from);
    const after = configById(to);
    if (!before || !after) continue;
    if (!configs.some((c) => c.id === from) || !configs.some((c) => c.id === to)) continue;
    push(
      `### \`${before.label}\` → \`${after.label}\``,
      '',
      `*${after.question}*`,
      '',
      `| Category | ${SCORES.map((score) => `Δ\`${score.replace('Score', '')}\``).join(' | ')} |`,
      `| --- | ${SCORES.map(() => '---').join(' | ')} |`,
    );
    for (const category of categories) {
      const deltas = SCORES.map((score) => {
        const a = valuesFor(results, from, score, (row) => row.category === category);
        const b = valuesFor(results, to, score, (row) => row.category === category);
        if (a.length > 0 && b.length > 0) {
          const delta = mean(b) - mean(a);
          return `${delta >= 0 ? '+' : ''}${delta.toFixed(2)}`;
        }
        // A score only one side measures has no delta. Printing 0 would say the
        // layer changed nothing when it was the first to look at all.
        if (b.length > 0) return `${mean(b).toFixed(2)} new`;
        if (a.length > 0) return `${mean(a).toFixed(2)} gone`;
        return '—';
      });
      push(`| \`${category}\` | ${deltas.join(' | ')} |`);
    }
    push('');
  }
  push(
    'A number is a delta between the two configurations. `new` means the second configuration measured',
    'that score and the first did not, so only a level exists; `gone` is the reverse; `—` means neither',
    'measured it. The `baseline` rows are almost all `new` by construction: with every layer switched off',
    'there is nothing to compare against, which is what makes it a useful reference point.',
    '',
  );

  // ---- false positives -------------------------------------------------------
  push(
    '## 6. False positives on human-written samples',
    '',
    `A **tell** that fires on \`human-written\` text is a false positive, and it is listed by name because a`,
    'count cannot be acted on. Under `full`.',
    '',
  );
  const humanFlags = flaggedHumanRules(results, 'full');
  // Voice-distance rules are separated out. They are not tells — they say "this
  // text is not the profile's writer", which is true of every sample measured
  // against a profile learned leave-one-out from the others. Listing them beside
  // a real false positive would inflate the count and hide the real ones.
  const voiceRuleIds = new Set(
    results
      .flatMap((row) => row.findings)
      .filter((finding) => finding.ruleId.startsWith('stylometry.fingerprint'))
      .map((finding) => finding.ruleId),
  );
  const tellFlags = humanFlags.filter((tally) => !voiceRuleIds.has(tally.ruleId));
  const voiceFlags = humanFlags.filter((tally) => voiceRuleIds.has(tally.ruleId));

  if (tellFlags.length === 0) {
    push('No tell fired on any human-written sample.', '');
  } else {
    push('| Rule | Family | Human samples | Which |', '| --- | --- | --- | --- |');
    for (const tally of tellFlags) {
      push(
        `| \`${tally.ruleId}\` | ${tally.family} | ${tally.firings} | ${tally.samples.map((s) => `\`${s}\``).join(', ')} |`,
      );
    }
    push('');
  }
  if (voiceFlags.length > 0) {
    push(
      'Separately, the voice-distance rules fired on human-written samples:',
      '',
      '| Rule | Human samples | Which |',
      '| --- | --- | --- |',
    );
    for (const tally of voiceFlags) {
      push(
        `| \`${tally.ruleId}\` | ${tally.firings} | ${tally.samples.map((s) => `\`${s}\``).join(', ')} |`,
      );
    }
    push(
      '',
      'These are **not** false positives in the sense above. `voiceScore` is measured against a profile',
      'learned leave-one-out from the corpus\'s other human-written samples, so every sample is by',
      'construction not that writer — a human text scoring below 1 here is the measurement working, not a',
      'rule misfiring. They are also charged to `voiceScore` alone and never to `antiAIScore`, which is what',
      'the `+0.00` antiAIScore deltas in §5\'s voice rows show.',
      '',
    );
  }
  const humanRows = results.filter(
    (row) => row.configId === 'full' && row.provenance === CONTROL_PROVENANCE,
  );
  const flaggedHumans = humanRows.filter(
    (row) => !row.unmeasured.includes('antiAIScore') && row.scores.antiAIScore < FLAGGED_ANTI_AI,
  );
  push(
    `Samples flagged as AI-flavoured (antiAIScore < ${FLAGGED_ANTI_AI}) under \`full\`: ` +
      `${flaggedHumans.length} of ${humanRows.length} human-written samples.`,
    '',
  );
  for (const row of flaggedHumans) {
    push(
      `- \`${row.sampleId}\` (${row.category}, ${row.language}): antiAIScore ${row.scores.antiAIScore.toFixed(2)}, ` +
        `${row.findings.length} finding(s) — ${row.findings.map((finding) => `\`${finding.ruleId}\``).join(', ')}`,
    );
  }
  if (flaggedHumans.length > 0) push('');

  // ---- assistant-shaped ------------------------------------------------------
  const behaviorRows = results.filter(
    (row) => row.configId === 'full' && !row.unmeasured.includes('behaviorScore'),
  );
  const shaped = behaviorRows.filter((row) => row.scores.behaviorScore < ASSISTANT_SHAPED);
  push(
    '### Behaviour',
    '',
    `Under \`full\`, ${behaviorRows.length} sample(s) had a measurable \`behaviorScore\`, and ` +
      `${shaped.length} scored below ${ASSISTANT_SHAPED} (assistant-shaped):`,
    '',
  );
  const byCategory = new Map<string, { total: number; shaped: number }>();
  for (const row of behaviorRows) {
    const entry = byCategory.get(row.category) ?? { total: 0, shaped: 0 };
    entry.total += 1;
    if (row.scores.behaviorScore < ASSISTANT_SHAPED) entry.shaped += 1;
    byCategory.set(row.category, entry);
  }
  push('| Category | Measurable | Assistant-shaped |', '| --- | --- | --- |');
  for (const [category, entry] of [...byCategory.entries()].sort()) {
    push(`| \`${category}\` | ${entry.total} | ${entry.shaped} |`);
  }
  push('');

  // ---- the round trip --------------------------------------------------------
  // `full` measures the *candidate* for samples that have one, and
  // `+anti-ai+behavior` measures the original. The difference is what the rewrite
  // did, which is the only part of this document that speaks to whether the
  // contract works rather than whether the detectors do.
  const rewriteRows = results.filter(
    (row) => row.configId === 'full' && row.preservationMeasured,
  );
  let ruleSection = 7;
  if (rewriteRows.length > 0) {
    push(
      '## 7. What the rewrite changed',
      '',
      'For the samples with a recorded candidate, `full` measures the rewritten text and',
      '`+anti-ai+behavior` measures the original, so the difference is the rewrite itself.',
      '',
      'The candidates were produced by a model applying the contract the suite emitted — one pass, no',
      'retry — and they are files in `benchmarks/candidates/` with their origin recorded. This is the only',
      'table here that says anything about whether the *contract* works rather than whether the detectors',
      'do.',
      '',
      '| Sample | antiAIScore | behaviorScore | voiceScore | preservationScore |',
      '| --- | --- | --- | --- | --- |',
    );
    const originals = new Map<string, SampleResult>();
    const voiced = new Map<string, SampleResult>();
    for (const row of results) {
      if (row.configId === 'anti-ai+behavior') originals.set(row.sampleId, row);
      // `voiceScore` needs a baseline that also had a profile attached, or the
      // column would be a dash on every row and would say nothing.
      if (row.configId === 'anti-ai+voice') voiced.set(row.sampleId, row);
    }
    let improved = 0;
    let degraded = 0;
    for (const row of [...rewriteRows].sort((a, b) => compareText(a.sampleId, b.sampleId))) {
      const before = originals.get(row.sampleId);
      if (!before) continue;
      const cell = (score: ScoreName, baseline: SampleResult | undefined): string => {
        if (score === 'preservationScore') {
          // The baseline is the original, which preserves itself by definition.
          // What is worth reading is whether the rewrite did.
          return row.unmeasured.includes(score)
            ? '— (nothing to preserve)'
            : row.scores[score].toFixed(2);
        }
        if (!baseline || baseline.unmeasured.includes(score) || row.unmeasured.includes(score)) {
          return '—';
        }
        const delta = row.scores[score] - baseline.scores[score];
        return (
          `${baseline.scores[score].toFixed(2)} → ${row.scores[score].toFixed(2)}` +
          (Math.abs(delta) < 0.005 ? '' : ` (${delta > 0 ? '+' : ''}${delta.toFixed(2)})`)
        );
      };
      if (row.scores.antiAIScore > before.scores.antiAIScore + 0.005) improved += 1;
      if (row.scores.antiAIScore < before.scores.antiAIScore - 0.005) degraded += 1;
      push(
        `| \`${row.sampleId}\` | ${cell('antiAIScore', before)} | ${cell('behaviorScore', before)} | ` +
          `${cell('voiceScore', voiced.get(row.sampleId))} | ${cell('preservationScore', before)} |`,
      );
    }
    push(
      '',
      `\`antiAIScore\` rose on **${improved}** of the ${rewriteRows.length} rewritten sample(s) and fell on ` +
        `**${degraded}**. A fall is not automatically a failure — a rewrite can trade one tell for a`,
      'different one while reading better, and `voiceScore` and `preservationScore` are where that shows.',
      'What matters is that all four numbers are visible at once, which is why they are never fused.',
      '',
      'The `antiAIScore` and `behaviorScore` columns compare against `+anti-ai+behavior` on the original,',
      'and `voiceScore` against `+anti-ai+voice`, which is the configuration that also had a profile',
      'attached. `preservationScore` has no baseline to compare with — the original preserves itself — so',
      'it shows the rewritten text\'s own value, and it is the column where the two planted failures in',
      '`benchmarks/candidates/` are visible.',
      '',
      `Sample size: **${rewriteRows.length}**. This is an illustration, not a measurement of the contract,`,
      'and it is the table a larger corpus would most obviously improve.',
      '',
    );
    ruleSection = 8;
  }

  // ---- rule exercise ---------------------------------------------------------
  const tallies = tallyRules(results, 'full');
  push(
    `## ${ruleSection}. Which rules the corpus exercises`,
    '',
    `${tallies.length} of ${meta.ruleCount} canonical rules produced at least one finding under \`full\`.`,
    'An unexercised rule is not necessarily wrong — the corpus may simply not contain that tell — but it is',
    'untested against real text, and the count belongs in the record rather than in a footnote.',
    '',
    '| Rule | Family | Samples | Categories |',
    '| --- | --- | --- | --- |',
  );
  for (const tally of tallies) {
    push(
      `| \`${tally.ruleId}\` | ${tally.family} | ${tally.firings} | ${tally.categories.join(', ')} |`,
    );
  }
  push('');

  // ---- rules that declined to decide ------------------------------------------
  //
  // Printed beside the firing table, because a reader who sees a rule's count fall has to be
  // able to tell "the corpus stopped tripping it" from "the rule stopped looking". An
  // abstention is a third outcome, and a report that showed only firings would print it as
  // silence.
  const abstentions = tallyAbstentions(results);
  push(
    `## ${ruleSection + 1}. Which rules declined to decide`,
    '',
    'A context-dependent rule can be unable to reach a verdict: it needs evidence the caller did',
    'not supply, and abstains rather than treating a missing input as a negative result. An',
    'abstention is **neither a finding nor a pass**, and it is not counted anywhere in the scores.',
    '',
  );
  if (abstentions.length === 0) {
    push(
      results.some((entry) => entry.abstained === undefined)
        ? 'This run file predates abstention recording, so nothing can be said about what abstained in it.'
        : 'No rule abstained in this run: every rule the corpus exercises had the evidence it needed.',
      '',
    );
  } else {
    push('| Rule | Measurements | State | From |', '| --- | --- | --- | --- |');
    for (const entry of abstentions) {
      push(`| \`${entry.ruleId}\` | ${entry.count} | \`${entry.state}\` | \`${entry.source}\` |`);
    }
    push(
      '',
      '`unknown` means the rule had no evidence to decide on. It is not a negative result, and these',
      'measurements are excluded from every other table in this document: they are not firings that',
      'were suppressed, and they are not samples where the rule looked and found nothing.',
      '',
      'For `chat.unsolicited_advice` the state comes from the sample\'s `advice_permission`, read from the',
      'solution-permission layer A v1 and recorded in the corpus front matter. `explicit` is a sample that',
      'records `unknown`; `default` is one that records nothing, which is every sample with no user turn and',
      'every configuration that does not supply a conversation. Neither is evidence that advice was uninvited.',
      '',
    );
  }

  // ---- reproduce -------------------------------------------------------------
  push(
    '## ' + (ruleSection + 2) + '. Reproducing this',
    '',
    '```bash',
    '# 1. populate the upstream cache (the samples vendored from it are already committed)',
    'npm run upstream:check',
    '',
    '# 2. run the ablation matrix; writes benchmarks/runs/<timestamp>-<hash>.json',
    'npm run bench:run',
    '',
    '# 3. answer the ablation questions from the stored run',
    'npm run bench:ablation',
    '',
    '# 4. render this file from the same stored run',
    'npm run bench:report',
    '```',
    '',
    `This document was rendered from \`benchmarks/runs/${run.file}\` over corpus \`${meta.corpusHash}\`.`,
    'A run over a different corpus hash is a different experiment and must not be compared with this one.',
    '',
    meta.note,
    '',
  );

  return `${lines.join('\n')}\n`;
}

function main(): number {
  const options = parseArgs(process.argv.slice(2));

  // `--check` cannot verify anything without the run the report was rendered from, and `runs/` is
  // gitignored: a fresh checkout and every CI job have no run files at all. Saying so and exiting 0
  // is the honest answer — the absence of a run is not evidence that the report is stale — and it is
  // the same shape as `voice:check` on a checkout that never generated the author voices. Anywhere a
  // run *is* present, this stays a real gate.
  if (options.check && listRuns(path.join(ROOT, 'benchmarks')).length === 0) {
    process.stdout.write(
      `${options.out} cannot be verified in this checkout: benchmarks/runs/ is gitignored and holds no ` +
        'runs. Run `npm run bench:run` to produce one, then `npm run bench:report -- --check`.\n',
    );
    return 0;
  }

  const run = loadRun(path.join(ROOT, 'benchmarks'), options.runFile);
  const markdown = render(run);

  if (options.check) {
    let existing: string | null = null;
    try {
      existing = readFileSync(options.out, 'utf8');
    } catch {
      existing = null;
    }
    if (existing === null) {
      process.stdout.write(`${options.out} does not exist. Run without --check to create it.\n`);
      return 1;
    }
    if (existing !== markdown) {
      process.stdout.write(`${options.out} is stale. Run npm run bench:report to regenerate it.\n`);
      return 1;
    }
    process.stdout.write(`${options.out} is current.\n`);
    return 0;
  }

  writeFileSync(options.out, markdown, 'utf8');
  process.stdout.write(
    `Rendered ${options.out} from benchmarks/runs/${run.file} (${run.results.length} measurements).\n`,
  );
  return 0;
}

try {
  process.exit(main());
} catch (error) {
  process.stderr.write(`bench:report failed: ${String(error)}\n`);
  process.exit(1);
}


